    echo -e "${GREEN}========================================================================${NC}"
    echo -e "${GREEN}   🚀 000-MISSION-CONTROL DEPLOYED SUCCESSFULLY ON VPS!                 ${NC}"
    echo -e "${GREEN}========================================================================${NC}"
    echo ""
    echo -e "  🌐 Dashboard URL:    ${CYAN}https://${DOMAIN_NAME}${NC}"
    if [[ "$DOMAIN_NAME" == "000.localhost" || "$DOMAIN_NAME" == "localhost" ]]; then
      echo -e "  🌐 Local Fallback:  ${CYAN}http://localhost:80${NC}"
    fi
    echo -e "  🔒 Security Engine:  ${GREEN}WebCrypto AES-GCM-256 (Zero-Knowledge)${NC}"
    echo -e "  📡 Edge Proxy:       ${GREEN}Caddy 2.8 with Auto-SSL & HTTP/3 QUIC${NC}"
    echo -e "  📁 Containers:       ${CYAN}000_app (Nginx), 000_caddy (Proxy)${NC}"
